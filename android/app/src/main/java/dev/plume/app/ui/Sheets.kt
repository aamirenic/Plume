@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PlumeSheet(
    title: String,
    subtitle: String,
    onDismiss: () -> Unit,
    content: @Composable ColumnScope.() -> Unit,
) {
    ModalBottomSheet(
        onDismissRequest = onDismiss,
        sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true),
        containerColor = PlumeColors.Panel,
        contentColor = PlumeColors.Ivory,
        dragHandle = {
            Box(
                Modifier
                    .padding(top = 10.dp, bottom = 6.dp)
                    .width(42.dp)
                    .height(3.dp)
                    .clip(RoundedCornerShape(2.dp))
                    .background(PlumeColors.Line),
            )
        },
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 20.dp)
                .padding(bottom = 28.dp),
        ) {
            Text(
                text = title,
                style = MaterialTheme.typography.headlineMedium,
                color = PlumeColors.Ivory,
            )
            if (subtitle.isNotEmpty()) {
                Spacer(Modifier.height(4.dp))
                Text(
                    text = subtitle,
                    style = MaterialTheme.typography.bodyMedium,
                    color = PlumeColors.Muted,
                )
            }
            Spacer(Modifier.height(12.dp))
            RibbonDivider(Modifier.fillMaxWidth().height(2.dp))
            Spacer(Modifier.height(14.dp))
            content()
        }
    }
}

@Composable
fun GallerySheet(
    state: EditorState,
    onDismiss: () -> Unit,
    onLoad: (String) -> Unit,
) {
    PlumeSheet(
        title = "Start from a scene",
        subtitle = "Every scene is generated by PLUME's own curve engine. Loading one replaces the current scene; your previous work stays in autosave until you edit again.",
        onDismiss = onDismiss,
    ) {
        LazyVerticalGrid(
            columns = GridCells.Fixed(2),
            modifier = Modifier.fillMaxWidth().heightIn(max = 520.dp),
            horizontalArrangement = Arrangement.spacedBy(10.dp),
            verticalArrangement = Arrangement.spacedBy(10.dp),
        ) {
            gridItems(state.gallery, key = { it.id }) { entry ->
                val selected = state.info?.name == entry.name
                Column(
                    modifier = Modifier
                        .clip(RoundedCornerShape(10.dp))
                        .background(if (selected) PlumeColors.PanelHigh else PlumeColors.InkSoft)
                        .clickable { onLoad(entry.id) }
                        .padding(6.dp),
                ) {
                    val bitmap = state.galleryThumbs[entry.id]
                    Box(
                        modifier = Modifier
                            .fillMaxWidth()
                            .aspectRatio(1.55f)
                            .clip(RoundedCornerShape(7.dp))
                            .background(PlumeColors.Ink),
                    ) {
                        if (bitmap != null) {
                            Image(
                                bitmap = bitmap.asImageBitmap(),
                                contentDescription = entry.name,
                                modifier = Modifier.fillMaxWidth().aspectRatio(1.55f),
                                contentScale = ContentScale.Crop,
                            )
                        } else {
                            BrushSwatch(
                                modifier = Modifier.fillMaxWidth().height(74.dp).padding(12.dp),
                                color = PlumeColors.Faint,
                            )
                        }
                    }
                    Spacer(Modifier.height(7.dp))
                    Text(
                        text = entry.name,
                        style = MaterialTheme.typography.titleMedium,
                        color = if (selected) PlumeColors.Coral else PlumeColors.Ivory,
                        maxLines = 1,
                    )
                    Text(
                        text = entry.category.uppercase(Locale.US),
                        style = MaterialTheme.typography.labelSmall,
                        color = PlumeColors.Teal,
                    )
                }
            }
        }
    }
}

@Composable
fun BrushSheet(
    state: EditorState,
    onDismiss: () -> Unit,
    onSelect: (String) -> Unit,
) {
    val grouped = state.brushes.groupBy { it.category }
    PlumeSheet(
        title = "Brushes",
        subtitle = "Thirty built-in profiles share the same tapered extrusion, pattern, and pressure pipeline as the desktop studio.",
        onDismiss = onDismiss,
    ) {
        LazyColumn(modifier = Modifier.fillMaxWidth().heightIn(max = 540.dp)) {
            grouped.forEach { (category, brushes) ->
                item(key = "header-$category") {
                    Text(
                        text = category.uppercase(Locale.US),
                        style = MaterialTheme.typography.labelSmall,
                        color = PlumeColors.Gold,
                        modifier = Modifier.padding(top = 12.dp, bottom = 4.dp),
                    )
                }
                listItems(brushes, key = { it.id }) { brush ->
                    val selected = brush.id == state.selectedBrush
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .clip(RoundedCornerShape(8.dp))
                            .background(if (selected) PlumeColors.PanelHigh else Color.Transparent)
                            .clickable { onSelect(brush.id) }
                            .padding(horizontal = 8.dp, vertical = 7.dp),
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
                        Box(
                            modifier = Modifier
                                .size(width = 74.dp, height = 32.dp)
                                .clip(RoundedCornerShape(6.dp))
                                .background(PlumeColors.InkSoft),
                        ) {
                            BrushSwatch(
                                modifier = Modifier.fillMaxWidth().height(32.dp).padding(horizontal = 7.dp),
                                color = if (selected) PlumeColors.Coral else PlumeColors.Ivory,
                                weight = (brush.size / 24f).coerceIn(0.15f, 1f),
                                dotted = category.contains("Dot", ignoreCase = true),
                                flat = category.contains("Wide", ignoreCase = true),
                            )
                        }
                        Spacer(Modifier.width(12.dp))
                        Column(Modifier.weight(1f)) {
                            Text(
                                text = brush.name,
                                style = MaterialTheme.typography.titleMedium,
                                color = PlumeColors.Ivory,
                            )
                            Text(
                                text = "${brush.size.toInt()} mm · ${brush.category}",
                                style = MaterialTheme.typography.bodyMedium,
                                color = PlumeColors.Muted,
                            )
                        }
                        if (selected) {
                            Text(
                                text = "IN USE",
                                style = MaterialTheme.typography.labelSmall,
                                color = PlumeColors.Coral,
                            )
                        }
                    }
                }
            }
        }
    }
}

@Composable
fun ExportSheet(
    onDismiss: () -> Unit,
    onPick: (ExportFormat) -> Unit,
) {
    PlumeSheet(
        title = "Send it out",
        subtitle = "Choose a format, then pick a destination with the system file picker. PLUME never uploads your work.",
        onDismiss = onDismiss,
    ) {
        Column(Modifier.fillMaxWidth()) {
            ExportFormat.entries.forEach { format ->
                Surface(
                    onClick = { onPick(format) },
                    color = PlumeColors.InkSoft,
                    shape = RoundedCornerShape(9.dp),
                    modifier = Modifier.fillMaxWidth().padding(vertical = 3.dp),
                ) {
                    Row(
                        modifier = Modifier.padding(horizontal = 12.dp, vertical = 11.dp),
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
                        Column(Modifier.weight(1f)) {
                            Text(
                                text = format.label,
                                style = MaterialTheme.typography.titleMedium,
                                fontWeight = FontWeight.Medium,
                                color = PlumeColors.Ivory,
                            )
                            Text(
                                text = format.detail,
                                style = MaterialTheme.typography.bodyMedium,
                                color = PlumeColors.Muted,
                            )
                        }
                        Text(
                            text = format.extension.uppercase(Locale.US),
                            style = MaterialTheme.typography.labelSmall,
                            color = PlumeColors.Teal,
                        )
                    }
                }
            }
        }
    }
}
